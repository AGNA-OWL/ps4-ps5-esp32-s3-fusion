#!/usr/bin/env python3
"""Generate a throwaway self-signed TLS certificate for the PS5 User Guide.

The certificate is embedded into src/server_certs.h.  It is intentionally
self-signed: the goal is to make manuals.playstation.net resolve to the ESP32
and be accepted by the console, not to provide real security.
"""
from __future__ import annotations

import argparse
import shutil
import subprocess
import tempfile
from pathlib import Path


def run(cmd: list[str]) -> None:
    subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)


def c_array(name: str, data: bytes) -> str:
    values = ",".join(f"0x{b:02x}" for b in data + b"\0")
    return (
        f"static const uint8_t {name}[] = {{{values}}};\n"
        f"static const size_t {name}_len = sizeof({name});\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("src/server_certs.h"))
    parser.add_argument("--days", type=int, default=3650)
    args = parser.parse_args()

    if shutil.which("openssl") is None:
        raise SystemExit("openssl is required to generate the embedded certificate")

    with tempfile.TemporaryDirectory() as tmp:
        tmp_path = Path(tmp)
        key = tmp_path / "server.key"
        crt = tmp_path / "server.crt"

        run(["openssl", "ecparam", "-name", "prime256v1", "-genkey", "-noout", "-out", str(key)])
        run([
            "openssl", "req", "-new", "-x509", "-sha256",
            "-days", str(args.days), "-key", str(key), "-out", str(crt),
            "-subj", "/CN=manuals.playstation.net",
            "-addext",
            "subjectAltName=DNS:manuals.playstation.net,DNS:ena.net.playstation.net,IP:192.168.4.1",
        ])

        header = (
            "// Generated by tools/gen_certs.py. Do not edit by hand.\n"
            "// Throwaway self-signed certificate for a local-only captive portal.\n"
            "#pragma once\n\n"
            "#include <stddef.h>\n"
            "#include <stdint.h>\n\n"
            + c_array("server_crt", crt.read_bytes())
            + "\n"
            + c_array("server_key", key.read_bytes())
        )
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(header, encoding="ascii")
        print(f"wrote {args.output} ({len(crt.read_bytes())} B cert, {len(key.read_bytes())} B key)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
